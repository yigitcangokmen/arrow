// Runs before dev and build. Dependency-free. Missing sources become null / empty, never a build error.
import { createRequire } from "node:module";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..");
const repo = join(web, "..");
const require = createRequire(import.meta.url);

const readJson = (p) => {
  try {
    return JSON.parse(readFileSync(p, "utf8"));
  } catch {
    return null;
  }
};
const filesIn = (dir, ext) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(ext)).sort() : []);

// 1. DCAP verifier wasm, served at /dcap/ so init({ module_or_path }) can fetch it (WS5-T07).
mkdirSync(join(web, "public/dcap"), { recursive: true });
const dcapPkg = dirname(require.resolve("@phala/dcap-qvl-web/package.json"));
copyFileSync(join(dcapPkg, "dcap-qvl-web_bg.wasm"), join(web, "public/dcap/dcap-qvl-web_bg.wasm"));

// 2. Synthetic demo files only (each carries a `synthetic` marker, checked in WS6-T01).
mkdirSync(join(web, "public/demo"), { recursive: true });
for (const f of filesIn(join(repo, "fixtures/demo"), ".csv")) copyFileSync(join(repo, "fixtures/demo", f), join(web, "public/demo", f));

// 3. Data modules the pages import instead of reading files at runtime.
const team = readJson(join(repo, "evidence/team-accounts.json"));
const teamAccounts = team ? [...(team.near ?? []), ...(team.evm ?? []).map((e) => e.address)] : [];
const bench = {};
for (const f of filesIn(join(repo, "bench/results"), ".json")) bench[basename(f)] = readJson(join(repo, "bench/results", f));
const criteria = {};
for (const f of filesIn(join(repo, "fixtures/criteria"), ".json")) criteria[basename(f, ".json")] = readJson(join(repo, "fixtures/criteria", f));

// /verify: release/sha256.txt exists only after the wasm freeze; without it row R1 stays NOT PROVEN.
let releaseSha256 = null;
try {
  releaseSha256 = readFileSync(join(repo, "release/sha256.txt"), "utf8").trim().split(/\s+/)[0] || null;
} catch {
  // not frozen yet
}

mkdirSync(join(web, "generated"), { recursive: true });
writeFileSync(
  join(web, "generated/data.ts"),
  `// Generated by scripts/copy-assets.mjs. Do not edit; not committed.
export const evidence: { mainnet: unknown; testnet: unknown } = ${JSON.stringify({
    mainnet: readJson(join(repo, "evidence/mainnet.json")),
    testnet: readJson(join(repo, "evidence/testnet.json")),
  })};
export const teamAccounts: string[] = ${JSON.stringify(teamAccounts)};
export const bench: Record<string, unknown> = ${JSON.stringify(bench)};
export const criteria: Record<string, unknown> = ${JSON.stringify(criteria)};
export const releaseSha256: string | null = ${JSON.stringify(releaseSha256)};
`,
);
console.log(`copy-assets: dcap wasm, ${filesIn(join(repo, "fixtures/demo"), ".csv").length} demo csv, ${Object.keys(bench).length} bench, ${Object.keys(criteria).length} criteria`);
