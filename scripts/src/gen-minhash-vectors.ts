// Generates fixtures/minhash-vectors.json and embeds the parameters into sdk/src/minhash-params.ts (WS4-T03).
// The vector math is written out here on purpose (node:crypto + BigInt, params read straight from
// fixtures/minhash-params.json) so the vectors do not come from the sdk function they test.
// Usage: npx tsx scripts/src/gen-minhash-vectors.ts [--check] [--emit-ts]
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const PARAMS_FILE = resolve(ROOT, "fixtures/minhash-params.json");
const VECTORS_FILE = resolve(ROOT, "fixtures/minhash-vectors.json");
const TS_FILE = resolve(ROOT, "sdk/src/minhash-params.ts");

const params = JSON.parse(readFileSync(PARAMS_FILE, "utf8")) as { k: number; prime: string; a: string[]; b: string[] };
const P = BigInt(params.prime);
const sha = (s: string) => createHash("sha256").update(s, "utf8").digest();

const normalize = (s: string) => s.trim().normalize("NFKC").toLowerCase().replace(/\s+/gu, " ");
const u64 = (key: string) => sha(normalize(key)).readBigUInt64BE(0);
const hex16 = (x: bigint) => x.toString(16).padStart(16, "0");

function signatureHex(keys: string[]): string {
  const xs = [...new Set(keys.map(u64))];
  let out = "";
  for (let i = 0; i < params.k; i++) {
    let min = (1n << 64n) - 1n;
    for (const x of xs) {
      const h = (BigInt(params.a[i]) * x + BigInt(params.b[i])) % P;
      if (h < min) min = h;
    }
    out += hex16(min);
  }
  return out;
}

const range = (n: number) => Array.from({ length: n }, (_, i) => i);
const CASES: { id: string; keys: string[] }[] = [
  { id: "ascii_wallets_20", keys: range(20).map((i) => "0x" + sha(`arrow:mh:wallet:${i}`).toString("hex").slice(0, 40)) },
  { id: "turkish_case", keys: ["İstanbul", "ISTANBUL", "ıi"] },
  { id: "greek_final_sigma", keys: ["ΟΔΟΣ", "Οδός"] },
  { id: "fullwidth", keys: ["ＡＢＣ１２３", "abc123"] },
  { id: "nbsp_and_tab", keys: ["  a b\tc  ", "A B  C", "x  y"] },
  { id: "duplicates", keys: ["a", "a", "A", " a ", "b"] },
  { id: "deterministic_1000", keys: range(1000).map((i) => sha(`arrow:mh:${i}`).toString("hex")) },
  { id: "empty_set", keys: [] },
];

function vectorsJson(): string {
  const cases = CASES.map(({ id, keys }) => ({
    id,
    keys,
    normalized: keys.map(normalize),
    u64_hex: keys.map((k) => hex16(u64(k))),
    signature_hex: signatureHex(keys),
  }));
  return JSON.stringify({ version: 1, note: "fixtures/README.md, MinHash (binding). Empty set = ff..ff x 128.", cases }, null, 2) + "\n";
}

function paramsTs(): string {
  const arr = (a: string[]) => `[\n${a.map((v) => `    "${v}",`).join("\n")}\n  ]`;
  return (
    "// Generated by scripts/src/gen-minhash-vectors.ts --emit-ts from fixtures/minhash-params.json. Do not edit.\n" +
    `export const MINHASH_PARAMS = {\n  k: ${params.k},\n  prime: "${params.prime}",\n  a: ${arr(params.a)},\n  b: ${arr(params.b)},\n} as const;\n`
  );
}

const read = (f: string) => {
  try {
    return readFileSync(f, "utf8");
  } catch {
    return null;
  }
};

if (process.argv.includes("--check")) {
  const bad = [read(VECTORS_FILE) !== vectorsJson() && "fixtures/minhash-vectors.json", read(TS_FILE) !== paramsTs() && "sdk/src/minhash-params.ts"].filter(Boolean);
  if (bad.length) {
    console.error(`DIFFERS from the generator: ${bad.join(", ")}`);
    process.exit(1);
  }
  console.log("OK byte-equal");
} else if (process.argv.includes("--emit-ts")) {
  writeFileSync(TS_FILE, paramsTs());
  console.log("wrote sdk/src/minhash-params.ts");
} else {
  writeFileSync(VECTORS_FILE, vectorsJson());
  console.log(`wrote fixtures/minhash-vectors.json (${CASES.length} cases)`);
}
